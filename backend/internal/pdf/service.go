package pdf

import (
	"fmt"
	"os"
	"time"

	"github.com/google/uuid"
	"github.com/johnfercher/maroto/pkg/color"
	"github.com/johnfercher/maroto/pkg/consts"
	"github.com/johnfercher/maroto/pkg/pdf"
	"github.com/johnfercher/maroto/pkg/props"
)

type Service struct{}

func NewService() *Service {
	return &Service{}
}

type PrescriptionData struct {
	ID           uint
	Diagnosis    string
	DoctorName   string
	PatientName  string
	Medicines    []MedicineLine
	Instructions string
	Date         time.Time
}

type MedicineLine struct {
	Name     string
	Dosage   string
	Duration string
	Notes    string
}

// GeneratePrescription creates a PDF and returns the file path
func (s *Service) GeneratePrescription(data *PrescriptionData) (string, error) {
	m := pdf.NewMaroto(consts.Portrait, consts.A4)
	m.SetPageMargins(20, 10, 20)

	// Header
	m.RegisterHeader(func() {
		m.Row(20, func() {
			m.Col(12, func() {
				m.Text("Dr.Ayya e-Prescription", props.Text{
					Size:  18,
					Style: consts.Bold,
					Align: consts.Center,
				})
			})
		})
	})

	// Doctor & Patient Info
	m.Row(20, func() {
		m.Col(6, func() {
			m.Text(fmt.Sprintf("Doctor: %s", data.DoctorName), props.Text{Style: consts.Bold})
			m.Text(fmt.Sprintf("Date: %s", data.Date.Format("02 Jan 2006")), props.Text{Top: 5})
		})
		m.Col(6, func() {
			m.Text(fmt.Sprintf("Patient: %s", data.PatientName), props.Text{Style: consts.Bold, Align: consts.Right})
			m.Text(fmt.Sprintf("ID: %d", data.ID), props.Text{Align: consts.Right, Top: 5})
		})
	})

	m.Line(1.0)

	// Diagnosis
	m.Row(10, func() {
		m.Col(12, func() {
			m.Text("Diagnosis:", props.Text{Style: consts.Bold})
		})
	})
	m.Row(10, func() {
		m.Col(12, func() {
			m.Text(data.Diagnosis)
		})
	})

	m.Line(1.0)

	// Medicines Table
	header := []string{"Medicine", "Dosage", "Duration", "Instructions"}
	var contents [][]string
	for _, med := range data.Medicines {
		contents = append(contents, []string{med.Name, med.Dosage, med.Duration, med.Notes})
	}

	if len(contents) == 0 {
		contents = [][]string{{"No medicines prescribed", "-", "-", "-"}}
	}

	m.TableList(header, contents, props.TableList{
		HeaderProp: props.TableListContent{
			Size:      10,
			GridSizes: []uint{4, 2, 2, 4},
		},
		ContentProp: props.TableListContent{
			Size:      10,
			GridSizes: []uint{4, 2, 2, 4},
		},
		Align:              consts.Left,
		HeaderContentSpace: 1,
		Line:               true,
	})

	m.Line(1.0)

	// Footer
	m.RegisterFooter(func() {
		m.Row(10, func() {
			m.Col(12, func() {
				m.Text("Generated by Dr.Ayya AI", props.Text{
					Size:  8,
					Color: color.NewWhite(),
					Style: consts.Italic,
					Align: consts.Center,
				})
			})
		})
	})

	// Save File
	filename := fmt.Sprintf("storage/prescriptions/RX-%d-%s.pdf", data.ID, uuid.New().String()[:6])
	os.MkdirAll("storage/prescriptions", os.ModePerm)

	err := m.OutputFileAndClose(filename)
	if err != nil {
		return "", err
	}

	return filename, nil
}
